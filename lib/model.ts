// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value follows only from the snapshot's own figures. The base multiple is not a constant:
// it is calibrated from the snapshot itself. Every protocol whose token already trades is a peer;
// a peer's realised multiple is its market cap over its TVL. A category's multiple starts from the
// median of its peers' multiples, first winsorised to a third-to-three-times band around the global
// peer median (one wild peer, an oracle filed under Risk Curators, cannot outvote the market), then
// averaged with the global median weighted by peer_shrink_k pseudo-peers, and clamped to
// [multiple_floor, multiple_cap]. A category with many peers keeps most of its own signal; a
// category with no peers uses the global median.
//
//   multiple   = clamp((n x category_median + k x global_median) / (n + k))
//   growth     = clamp(change_7d, -50, 100) per cent
//   growthMult = 1 + (growth / 100) x 0.35
//   maturity   = 0.75 + min(age_days, 1460) / 1460 x 0.35   (age_days unknown: 365)
//   breadth    = 1 + min(chains - 1, 5) x 0.04
//   implied    = max(1, round(tvl_usd x multiple x growthMult x maturity x breadth))
//
// The constants are stated in the dashboard. No protocol name is ever special-cased: the same
// function scores every row, and the calibration reads only the snapshot's own live-token peers.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
